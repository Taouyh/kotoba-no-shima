const seen = new Set<string>();
export const kanjiEntries: StudyEntry[] = blocks.flatMap(([lessonId, text]) =>
  text
    .trim()
    .split("\n")
    .flatMap((line) => {
      const [character, characterMeaning, term, reading, meaning] =
        line.split("|");
      // A character belongs to its first lesson; later illustrative words do not inflate the count.
      if (seen.has(character)) return [];
      seen.add(character);
      return [
        {
          id: `kanji-${character}`,
          lessonId,
          kind: "kanji" as const,
          character,
          term,
          reading,
          meaning,
          note: `「${character}」的常见含义：${characterMeaning}。本题练习代表词「${term}」的完整读音，不表示这个汉字只有一种读法。`,
          sourceIds: ["jlpt-level", "jlpt-faq"],
        },
      ];
    }),
);
