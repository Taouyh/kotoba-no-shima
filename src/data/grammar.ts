export const grammarEntries: StudyEntry[] = blocks.flatMap(([lessonId, text]) =>
  text
    .trim()
    .split("\n")
    .map((line) => {
      const [term, meaning, example, answer, distractors, note] =
        line.split("|");
      return {
        id: `${lessonId}-${term}`,
        lessonId,
        kind: "grammar" as const,
        term,
        reading: "",
        meaning,
        example,
        prompt: `请选择表示「${meaning}」的表达，补全句子。`,
        options: [answer, ...distractors.split(";")],
        answer,
        note,
        sourceIds: ["jlpt-level", "jlpt-faq"],
      };
    }),
);
